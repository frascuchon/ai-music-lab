#!/usr/bin/env python3
"""Turn tools/modal_freeze.py output into plugins-and-extensions/shared/modal_constraints/*.txt

    python3 tools/build_modal_constraints.py FREEZE_DIR

Each constraints file lists ``name==version`` for every package a model's image
contains (local version tags such as ``+cu121`` are dropped so the same pin
matches the index the script installs from). Direct references (git/URL/file
installs) cannot be constrained; they are listed as comments and must be pinned
by commit inside the script itself (tests enforce that).
"""
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "plugins-and-extensions" / "shared" / "modal_constraints"
# Build tooling: constraining these breaks isolated builds of other packages.
SKIP = {"pip", "setuptools", "wheel"}


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def lines_for(freeze: list[str]):
    pins, refs = {}, []
    for line in freeze:
        if "==" in line and " @ " not in line and not line.startswith("-e"):
            name, version = line.split("==", 1)
            if normalise(name) in SKIP:
                continue
            pins[normalise(name)] = version.split("+", 1)[0]
        else:
            refs.append(line)
    return pins, refs


def drop_stale_cuda(pins: dict) -> list[str]:
    """Remove ``nvidia-*-cu12`` packages when torch runs on the CUDA 13 stack.

    They are leftovers of an earlier layer (e.g. audiocraft installing torch 2.1.0
    before torch was upgraded) and ship files at the same paths as the CUDA 13
    packages (libnccl.so.2, ...). In the original sequential build the newer ones
    were written last; installing the whole set at once lets the stale ones win and
    torch then fails with ``undefined symbol: ncclCommResume``.
    """
    if not any(n.startswith("nvidia-") and n.endswith("-cu13") for n in pins):
        return []
    stale = [n for n in pins if n.startswith("nvidia-") and n.endswith("-cu12")]
    for n in stale:
        del pins[n]
    return stale


def write(path: Path, header: str, freeze: list[str]) -> None:
    pins, refs = lines_for(freeze)
    dropped = drop_stale_cuda(pins)
    body = [f"# {header}", "# Generated by tools/build_modal_constraints.py — do not edit by hand.",
            "# Applied through PIP_CONSTRAINT so rebuilding the image cannot pick newer releases."]
    if dropped:
        body.append(f"# Dropped stale CUDA 12 libraries (see drop_stale_cuda): {', '.join(sorted(dropped))}")
    body += [f"{n}=={v}" for n, v in sorted(pins.items())]
    direct = [r for r in refs if " @ git+" in r or " @ https" in r or r.startswith("-e git+")]
    if direct:
        body.append("# Direct references (cannot be constrained; pinned by commit in the script):")
        body += [f"# {r}" for r in direct]
    path.write_text("\n".join(body) + "\n")


def main(freeze_dir: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for f in sorted(Path(freeze_dir).glob("*.json")):
        data = json.loads(f.read_text())
        stem = Path(data["script"]).stem
        pythons = list(data["pythons"].items())
        if stem == "research_musecoco_modal":      # conda 3.8 + system 3.11
            for exe, p in pythons:
                suffix = ".conda" if "3.8" in p["version"][:3] else ".system"
                write(OUT / f"{stem}{suffix}.txt",
                      f"{stem} — {exe} (Python {p['version']})", p["freeze"])
        else:
            exe, p = pythons[0]
            write(OUT / f"{stem}.txt", f"{stem} — Python {p['version']}", p["freeze"])
        print("wrote", stem)


if __name__ == "__main__":
    main(sys.argv[1])
